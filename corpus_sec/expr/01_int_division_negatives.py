print(7 // 3)      # 2
print(7 // -3)     # -3 (floor division)
print(-7 // 3)     # -3 (floor division)
print(-7 // -3)    # 2
print(7 % 3)       # 1
print(7 % -3)      # -2 (mantiene el signo del divisor)
print(-7 % 3)      # 2
print(-7 % -3)     # -1