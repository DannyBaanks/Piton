print(2 ** 10)           # 1024
print(-2 ** 10)          # -1024 (unario, no parenthesizado)
print((-2) ** 10)        # 1024
print(3 ** 0.5)          # 1.7320508075688772
print(2 ** -1)           # 0.5
print(10 % 3)            # 1
print(10 % 0)            # ZeroDivisionError